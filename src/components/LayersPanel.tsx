import React from 'react';
import { View, Text, TouchableOpacity, StyleSheet, Image } from 'react-native';
import type { PaintLayer, LayerVisibility } from '../state/PaintingContext';

/**
 * Layers panel for the MAIN WORKSPACE only.
 *
 * Exactly three fixed rows, top-to-bottom Foreground / Middle Ground / Background —
 * i.e. reverse paint order, so the list reads the way the artwork stacks. The order is
 * FIXED: there is deliberately no reordering affordance anywhere in this component.
 *
 * Presentational on purpose. Every mutation is a callback so layer state stays in
 * PaintingContext and keeps flowing through the existing dispatches, which already feed
 * the shared painter history (see LayerHistoryEntry / applyLayerOperation there).
 *
 * Thumbnails are REAL rendered snapshots of each layer, generated by PaintScreen only while
 * this panel is open and only after the strokes settle. They arrive asynchronously, so a glyph
 * strip of the emoji painted on that layer is shown until the first snapshot lands — the row is
 * never blank, and nothing is re-rasterised on a pointer move.
 */

export type LayersPanelLayout = 'phone' | 'tabletPortrait' | 'tabletLandscape';

/** Long-press actions. Only the ones valid for a given layer are ever offered. */
export type LayerAction = 'copy' | 'paste' | 'clear' | 'mergeDown' | 'mergeUp' | 'duplicate';

interface LayersPanelProps {
  activeLayer: PaintLayer;
  visibility: LayerVisibility;
  /** Artwork strokes per layer (border-bounds plumbing already excluded). */
  counts: Record<PaintLayer, number>;
  /** Emoji painted on each layer — fallback shown until a snapshot exists. */
  previews: Record<PaintLayer, string[]>;
  /** Rendered snapshot per layer (data URI), or null while none has been generated yet. */
  thumbnails?: Record<PaintLayer, string | null>;
  layout: LayersPanelLayout;
  /** Row whose long-press menu is open, if any. */
  menuLayer: PaintLayer | null;
  /** Something is on the layer clipboard, so Paste is meaningful. */
  hasClipboard: boolean;
  onSelect: (layer: PaintLayer) => void;
  onToggleVisibility: (layer: PaintLayer) => void;
  onOpenMenu: (layer: PaintLayer) => void;
  onCloseMenu: () => void;
  onAction: (layer: PaintLayer, action: LayerAction) => void;
  onClose: () => void;
}

/** Top-to-bottom display order. NOT the paint order — see PAINT_LAYER_ORDER for that. */
const ROW_ORDER: readonly PaintLayer[] = ['foreground', 'middle', 'background'];

const ROW_LABEL: Record<PaintLayer, string> = {
  foreground: 'Foreground',
  middle: 'Middle Ground',
  background: 'Background'
};

const LAYOUT_WIDTH: Record<LayersPanelLayout, number> = {
  phone: 236,
  tabletPortrait: 340,
  tabletLandscape: 280
};

const ACTION_LABEL: Record<LayerAction, string> = {
  copy: 'Copy',
  paste: 'Paste',
  clear: 'Clear',
  mergeDown: 'Merge Down',
  mergeUp: 'Merge Up',
  duplicate: 'Duplicate'
};

/**
 * Fixed per-layer action sets. Middle Ground deliberately has no merge entry: it is the
 * anchor both other layers merge INTO, so it must never move.
 */
const ACTIONS_FOR: Record<PaintLayer, readonly LayerAction[]> = {
  foreground: ['copy', 'duplicate', 'clear', 'mergeDown'],
  middle: ['copy', 'paste', 'duplicate', 'clear'],
  background: ['copy', 'duplicate', 'clear', 'mergeUp']
};

const LayersPanel: React.FC<LayersPanelProps> = ({
  activeLayer,
  visibility,
  counts,
  previews,
  thumbnails,
  layout,
  menuLayer,
  hasClipboard,
  onSelect,
  onToggleVisibility,
  onOpenMenu,
  onCloseMenu,
  onAction,
  onClose
}) => {
  const compact = layout === 'phone';

  return (
    <View style={[styles.card, { width: LAYOUT_WIDTH[layout] }]}>
      <View style={styles.header}>
        <Text style={[styles.title, compact && styles.titleCompact]}>LAYERS</Text>
        <TouchableOpacity
          style={styles.closeButton}
          onPress={onClose}
          accessibilityRole="button"
          accessibilityLabel="Close layers panel"
        >
          <Text style={styles.closeIcon}>✕</Text>
        </TouchableOpacity>
      </View>

      {ROW_ORDER.map((layer) => {
        const selected = layer === activeLayer;
        const shown = visibility[layer];
        const glyphs = previews[layer];
        const snapshot = thumbnails?.[layer] ?? null;
        const isMenuOpen = menuLayer === layer;

        return (
          <View key={layer}>
            <TouchableOpacity
              style={[styles.row, selected && styles.rowSelected]}
              onPress={() => onSelect(layer)}
              onLongPress={() => onOpenMenu(layer)}
              delayLongPress={350}
              accessibilityRole="button"
              accessibilityState={{ selected }}
              accessibilityLabel={`${ROW_LABEL[layer]}, ${counts[layer]} strokes, ${shown ? 'visible' : 'hidden'}`}
            >
              <TouchableOpacity
                style={[styles.eyeButton, !shown && styles.eyeButtonOff]}
                onPress={() => onToggleVisibility(layer)}
                hitSlop={HIT_SLOP}
                accessibilityRole="button"
                accessibilityLabel={`${shown ? 'Hide' : 'Show'} ${ROW_LABEL[layer]}`}
              >
                <Text style={styles.eyeIcon}>{shown ? '👁' : '🚫'}</Text>
              </TouchableOpacity>

              <View style={styles.rowText}>
                <Text
                  style={[styles.rowLabel, compact && styles.rowLabelCompact, !shown && styles.rowLabelHidden]}
                  numberOfLines={1}
                >
                  {ROW_LABEL[layer]}
                </Text>
                <Text style={styles.rowCount}>
                  {counts[layer] === 0 ? 'empty' : `${counts[layer]} stroke${counts[layer] === 1 ? '' : 's'}`}
                </Text>
              </View>

              <View style={[styles.thumb, !shown && styles.thumbHidden]}>
                {snapshot ? (
                  // Real render of this layer. Falls back to the glyph strip while the
                  // debounced snapshot is still being generated, so the row is never blank.
                  <Image source={{ uri: snapshot }} style={styles.thumbImage} resizeMode="contain" />
                ) : glyphs.length === 0 ? (
                  <Text style={styles.thumbEmpty}>·</Text>
                ) : (
                  <Text style={styles.thumbGlyphs} numberOfLines={1}>
                    {glyphs.join('')}
                  </Text>
                )}
              </View>
            </TouchableOpacity>

            {isMenuOpen ? (
              <View style={styles.menu}>
                {ACTIONS_FOR[layer].map((action) => {
                  // Paste needs something copied; everything else needs content to act on.
                  const disabled = action === 'paste' ? !hasClipboard : counts[layer] === 0;
                  return (
                    <TouchableOpacity
                      key={action}
                      style={[styles.menuItem, disabled && styles.menuItemDisabled]}
                      disabled={disabled}
                      onPress={() => onAction(layer, action)}
                      accessibilityRole="button"
                      accessibilityLabel={`${ACTION_LABEL[action]} ${ROW_LABEL[layer]}`}
                    >
                      <Text style={styles.menuItemText}>{ACTION_LABEL[action]}</Text>
                    </TouchableOpacity>
                  );
                })}
                <TouchableOpacity
                  style={styles.menuItem}
                  onPress={onCloseMenu}
                  accessibilityRole="button"
                  accessibilityLabel="Close menu"
                >
                  <Text style={styles.menuDismissText}>Done</Text>
                </TouchableOpacity>
              </View>
            ) : null}
          </View>
        );
      })}
    </View>
  );
};

