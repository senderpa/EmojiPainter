#!/usr/bin/env ts-node
/**
 * Generates a TypeScript manifest of all logo sets in assets/logos/
 * Each subfolder becomes a logo set with its images sorted numerically
 */

import fs from 'node:fs';
import path from 'node:path';

const LOGOS_DIR = path.join(__dirname, '../assets/logos');
const LOGOSVIDEO_DIR = path.join(__dirname, '../assets/logosvideo');
const OUTPUT_FILE = path.join(__dirname, '../src/lib/logoManifest.ts');

interface ImageLogoSet {
  id: string;
  type: 'image';
  baseIcon: string;
  frames: string[];
}

interface VideoLogoSet {
  id: string;
  type: 'video';
  videoFile: string;
}

type LogoSet = ImageLogoSet | VideoLogoSet;

function scanLogosDirectory(): ImageLogoSet[] {
  if (!fs.existsSync(LOGOS_DIR)) {
    console.error(`❌ Logos directory not found: ${LOGOS_DIR}`);
    process.exit(1);
  }

  const subfolders = fs.readdirSync(LOGOS_DIR)
    .filter(name => {
      const fullPath = path.join(LOGOS_DIR, name);
      return fs.statSync(fullPath).isDirectory() && !name.startsWith('.');
    })
    .sort();

  console.log(`📁 Found ${subfolders.length} logo set folders`);

  const logoSets: ImageLogoSet[] = [];

  for (const folder of subfolders) {
    const folderPath = path.join(LOGOS_DIR, folder);
    const files = fs.readdirSync(folderPath)
      .filter(name => /\.(png|jpg|jpeg)$/i.test(name))
      .sort(); // Natural sort by filename

    if (files.length === 0) {
      console.warn(`⚠️  Skipping empty folder: ${folder}`);
      continue;
    }

    console.log(`  ✓ ${folder}: ${files.length} images`);

    logoSets.push({
      id: folder,
      type: 'image',
      baseIcon: files[0] || '', // First file = base icon
      frames: files.slice(1) // Rest = animation frames
    });
  }

  return logoSets;
}

function scanVideosDirectory(): VideoLogoSet[] {
  if (!fs.existsSync(LOGOSVIDEO_DIR)) {
    console.warn(`⚠️  Logosvideo directory not found: ${LOGOSVIDEO_DIR}`);
    return [];
  }

  const videoFiles = fs.readdirSync(LOGOSVIDEO_DIR)
    .filter(name => /\.mp4$/i.test(name) && !name.startsWith('.'))
    .sort();

  console.log(`🎬 Found ${videoFiles.length} video logo files`);

  const videoSets: VideoLogoSet[] = [];

  for (let i = 0; i < videoFiles.length; i++) {
    const videoFile = videoFiles[i];
    console.log(`  ✓ video_${i + 1}: ${videoFile}`);

    videoSets.push({
      id: `video_${i + 1}`,
      type: 'video',
      videoFile
    });
  }

  return videoSets;
}

function generateManifestCode(logoSets: LogoSet[]): string {
  const imports: string[] = [];
  const setDefinitions: string[] = [];

  for (const set of logoSets) {
    const setId = set.id;

    if (set.type === 'image') {
      // Generate import for base icon
      const baseVarName = `logo_${setId}_base`;
      imports.push(`import ${baseVarName} from '../../assets/logos/${setId}/${set.baseIcon}';`);

      // Generate imports for frames
      const frameVarNames: string[] = [];
      for (let i = 0; i < set.frames.length; i++) {
        const frameVarName = `logo_${setId}_frame_${i}`;
        imports.push(`import ${frameVarName} from '../../assets/logos/${setId}/${set.frames[i]}';`);
        frameVarNames.push(frameVarName);
      }

      // Create image set definition
      setDefinitions.push(`  {
    id: '${setId}',
    type: 'image' as const,
    baseIcon: ${baseVarName},
    frames: [${frameVarNames.join(', ')}]
  }`);
    } else if (set.type === 'video') {
      // Generate import for video file
      const videoVarName = `logo_${setId}_video`;
      imports.push(`import ${videoVarName} from '../../assets/logosvideo/${set.videoFile}';`);

      // Create video set definition
      setDefinitions.push(`  {
    id: '${setId}',
    type: 'video' as const,
    videoSource: ${videoVarName}
  }`);
    }
  }

  return `/**
 * AUTO-GENERATED FILE - DO NOT EDIT MANUALLY
 * Generated by scripts/generate-logo-manifest.ts
 * Run: npm run gen:logos
 */

${imports.join('\n')}

export type LogoSet = {
  id: string;
  type: 'image';
  baseIcon: any;
  frames: any[];
} | {
  id: string;
  type: 'video';
  videoSource: any;
};

export const LOGO_SETS: LogoSet[] = [
${setDefinitions.join(',\n')}
];

export function getRandomLogoSet(): LogoSet {
  return LOGO_SETS[Math.floor(Math.random() * LOGO_SETS.length)] || LOGO_SETS[0]!;
}

export function getLogoSetById(id: string): LogoSet | undefined {
  return LOGO_SETS.find(set => set.id === id);
}
`;
}

function main() {
  console.log('🎨 Generating logo manifest...\n');

  const imageLogoSets = scanLogosDirectory();
  const videoLogoSets = scanVideosDirectory();
  const allLogoSets: LogoSet[] = [...imageLogoSets, ...videoLogoSets];

  if (allLogoSets.length === 0) {
    console.error('❌ No logo sets found!');
    process.exit(1);
  }

  const code = generateManifestCode(allLogoSets);

  // Ensure output directory exists
  const outputDir = path.dirname(OUTPUT_FILE);
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  fs.writeFileSync(OUTPUT_FILE, code, 'utf-8');

  console.log(`\n✅ Generated manifest with ${allLogoSets.length} logo sets`);
  console.log(`   📁 ${imageLogoSets.length} image sets`);
  console.log(`   🎬 ${videoLogoSets.length} video sets`);
  console.log(`📄 Output: ${OUTPUT_FILE}`);
  console.log('\nImage logo sets:');
  for (const set of imageLogoSets) {
    console.log(`  • ${set.id}: 1 base + ${set.frames.length} frames`);
  }
  console.log('\nVideo logo sets:');
  for (const set of videoLogoSets) {
    console.log(`  • ${set.id}: ${set.videoFile}`);
  }
}

main();
