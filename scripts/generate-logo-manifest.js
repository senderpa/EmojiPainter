#!/usr/bin/env node
/**
 * Generates a TypeScript manifest of all logo sets in assets/logos/ (image frames)
 * and video logos in assets/logosvideo/ (MP4 files)
 */

const fs = require('fs');
const path = require('path');

const LOGOS_DIR = path.join(__dirname, '../assets/logos');
const VIDEOS_DIR = path.join(__dirname, '../assets/logosvideo');
const OUTPUT_FILE = path.join(__dirname, '../src/lib/logoManifest.ts');

function scanLogosDirectory() {
  if (!fs.existsSync(LOGOS_DIR)) {
    console.error(`❌ Logos directory not found: ${LOGOS_DIR}`);
    process.exit(1);
  }

  const subfolders = fs.readdirSync(LOGOS_DIR)
    .filter(name => {
      const fullPath = path.join(LOGOS_DIR, name);
      return fs.statSync(fullPath).isDirectory() && !name.startsWith('.');
    })
    .sort();

  console.log(`📁 Found ${subfolders.length} logo set folders`);

  const logoSets = [];

  for (const folder of subfolders) {
    const folderPath = path.join(LOGOS_DIR, folder);
    const files = fs.readdirSync(folderPath)
      .filter(name => /\.(png|jpg|jpeg)$/i.test(name))
      .sort(); // Natural sort by filename

    if (files.length === 0) {
      console.warn(`⚠️  Skipping empty folder: ${folder}`);
      continue;
    }

    console.log(`  ✓ ${folder}: ${files.length} images`);

    logoSets.push({
      id: folder,
      type: 'image',
      baseIcon: files[0] || '', // First file = base icon
      frames: files.slice(1) // Rest = animation frames
    });
  }

  return logoSets;
}

function scanVideosDirectory() {
  if (!fs.existsSync(VIDEOS_DIR)) {
    console.warn(`⚠️  Videos directory not found: ${VIDEOS_DIR} (skipping)`);
    return [];
  }

  const videoFiles = fs.readdirSync(VIDEOS_DIR)
    .filter(name => /\.(mp4|mov)$/i.test(name) && !name.startsWith('.'))
    .sort();

  console.log(`\n🎥 Found ${videoFiles.length} video files`);

  const videoSets = [];

  for (const file of videoFiles) {
    const id = `video_${videoSets.length + 1}`;
    console.log(`  ✓ ${id}: ${file}`);

    videoSets.push({
      id,
      type: 'video',
      videoFile: file
    });
  }

  return videoSets;
}

function generateManifestCode(logoSets, videoSets) {
  const imports = [];
  const setDefinitions = [];

  // Generate image-based logo sets
  for (const set of logoSets) {
    const setId = set.id;

    // Generate import for base icon
    const baseVarName = `logo_${setId}_base`;
    imports.push(`import ${baseVarName} from '../../assets/logos/${setId}/${set.baseIcon}';`);

    // Generate imports for frames
    const frameVarNames = [];
    for (let i = 0; i < set.frames.length; i++) {
      const frameVarName = `logo_${setId}_frame_${i}`;
      imports.push(`import ${frameVarName} from '../../assets/logos/${setId}/${set.frames[i]}';`);
      frameVarNames.push(frameVarName);
    }

    // Create set definition
    setDefinitions.push(`  {
    id: '${setId}',
    type: 'image' as const,
    baseIcon: ${baseVarName},
    frames: [${frameVarNames.join(', ')}]
  }`);
  }

  // Generate video-based logo sets
  for (const set of videoSets) {
    const setId = set.id;
    const videoVarName = `logo_${setId}_video`;

    // Import video file
    imports.push(`import ${videoVarName} from '../../assets/logosvideo/${set.videoFile}';`);

    // Create set definition
    setDefinitions.push(`  {
    id: '${setId}',
    type: 'video' as const,
    videoSource: ${videoVarName}
  }`);
  }

  return `/**
 * AUTO-GENERATED FILE - DO NOT EDIT MANUALLY
 * Generated by scripts/generate-logo-manifest.js
 * Run: npm run gen:logos
 */

import AsyncStorage from '@react-native-async-storage/async-storage';

${imports.join('\n')}

export type LogoSet = {
  id: string;
  type: 'image';
  baseIcon: any;
  frames: any[];
} | {
  id: string;
  type: 'video';
  videoSource: any;
};

export const LOGO_SETS: LogoSet[] = [
${setDefinitions.join(',\n')}
];

const USED_VIDEOS_KEY = '@logoManifest:usedVideos';

// Load used video logos from AsyncStorage
async function loadUsedVideoLogos(): Promise<Set<string>> {
  try {
    const stored = await AsyncStorage.getItem(USED_VIDEOS_KEY);
    if (stored) {
      const parsed = JSON.parse(stored);
      return new Set(parsed);
    }
  } catch (error) {
    console.warn('[LogoManifest] Failed to load used videos:', error);
  }
  return new Set();
}

// Save used video logos to AsyncStorage
async function saveUsedVideoLogos(usedLogos: Set<string>): Promise<void> {
  try {
    await AsyncStorage.setItem(USED_VIDEOS_KEY, JSON.stringify(Array.from(usedLogos)));
  } catch (error) {
    console.warn('[LogoManifest] Failed to save used videos:', error);
  }
}

// Reset used video logos tracking
async function resetUsedVideoLogos(): Promise<void> {
  try {
    await AsyncStorage.removeItem(USED_VIDEOS_KEY);
    console.log('[LogoManifest] ♻️ Reset video tracking - all videos available again');
  } catch (error) {
    console.warn('[LogoManifest] Failed to reset used videos:', error);
  }
}

export function getRandomLogoSet(): LogoSet {
  return LOGO_SETS[Math.floor(Math.random() * LOGO_SETS.length)] || LOGO_SETS[0];
}

export function getRandomImageLogoSet(): LogoSet {
  const imageSets = LOGO_SETS.filter(set => set.type === 'image');
  return imageSets[Math.floor(Math.random() * imageSets.length)] || LOGO_SETS[0];
}

export function getLogoSetById(id: string): LogoSet | undefined {
  return LOGO_SETS.find(set => set.id === id);
}

export async function getRandomLogoSetWithTracking(): Promise<LogoSet> {
  // Load tracking data
  const usedLogos = await loadUsedVideoLogos();

  // Filter to video logos only
  const videoLogos = LOGO_SETS.filter(set => set.type === 'video');

  // Filter out already-used videos
  const unusedVideoLogos = videoLogos.filter(logo => !usedLogos.has(logo.id));

  // If all videos used, reset and start over
  if (unusedVideoLogos.length === 0) {
    console.log('[LogoManifest] ♻️ All videos shown, resetting tracking');
    await resetUsedVideoLogos();
    return videoLogos[Math.floor(Math.random() * videoLogos.length)];
  }

  // Pick random unused video
  const selectedLogo = unusedVideoLogos[Math.floor(Math.random() * unusedVideoLogos.length)];

  // Mark as used
  usedLogos.add(selectedLogo.id);
  await saveUsedVideoLogos(usedLogos);

  console.log(\`[LogoManifest] 🎬 Selected video \${selectedLogo.id} (\${unusedVideoLogos.length - 1} remaining)\`);

  return selectedLogo;
}
`;
}

function main() {
  console.log('🎨 Generating logo manifest...\n');

  const logoSets = scanLogosDirectory();
  const videoSets = scanVideosDirectory();

  if (logoSets.length === 0 && videoSets.length === 0) {
    console.error('❌ No logo sets or videos found!');
    process.exit(1);
  }

  const code = generateManifestCode(logoSets, videoSets);

  // Ensure output directory exists
  const outputDir = path.dirname(OUTPUT_FILE);
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  fs.writeFileSync(OUTPUT_FILE, code, 'utf-8');

  console.log(`\n✅ Generated manifest with ${logoSets.length} image sets + ${videoSets.length} video sets`);
  console.log(`📄 Output: ${OUTPUT_FILE}`);
  console.log('\nImage logo sets:');
  for (const set of logoSets) {
    console.log(`  • ${set.id}: 1 base + ${set.frames.length} frames`);
  }
  if (videoSets.length > 0) {
    console.log('\nVideo logo sets:');
    for (const set of videoSets) {
      console.log(`  • ${set.id}: ${set.videoFile}`);
    }
  }
}

main();
